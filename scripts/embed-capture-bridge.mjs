import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, '..');

const sdkPath = join(root, 'packages/capture/dist/capture-bridge.iife.js');
const outputPath = join(root, 'src/lib/capture-bridge.generated.ts');

try {
  const sdkContent = readFileSync(sdkPath, 'utf-8');
  const escaped = sdkContent.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$/g, '\\$');

  const ts = `// Auto-generated by scripts/embed-capture-bridge.mjs — do not edit manually
export const CAPTURE_BRIDGE_IIFE: string = \`${escaped}\`;
`;

  writeFileSync(outputPath, ts, 'utf-8');
  console.log(`Generated ${outputPath} (${sdkContent.length} bytes)`);
} catch (err) {
  console.error('Failed to embed capture bridge:', err);
  process.exit(1);
}
